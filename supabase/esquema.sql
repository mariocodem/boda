-- Esquema de la invitación de Diego y Erika.
-- Pégalo completo en Supabase → SQL Editor → New query → Run.
--
-- Seguridad:
--  * La tabla invitados solo la pueden leer y escribir las cuentas listadas en
--    administradores (con sesión iniciada).
--  * Los invitados (anónimos) no tocan la tabla: usan dos funciones que solo
--    devuelven y modifican la invitación cuyo código conocen.
--  * La tabla evento (fecha, lugares y estilo) la puede leer cualquiera, como
--    la invitación impresa; solo los administradores la cambian.
--  * Las fotos van en el bucket público «fotos» de Storage: cualquiera con el
--    enlace las ve; solo los administradores las suben o las borran.
--
-- Se puede volver a ejecutar completo sin perder datos.

create extension if not exists pgcrypto;

create table if not exists public.invitados (
  id            uuid primary key default gen_random_uuid(),
  numero        integer generated by default as identity unique,
  codigo        text not null unique check (codigo ~ '^[A-Z0-9]{6,12}$'),
  nombre        text not null check (char_length(nombre) between 1 and 120),
  cupos         integer not null default 1 check (cupos between 1 and 20),
  telefono      text,
  lado          text not null default 'ambos' check (lado in ('diego', 'erika', 'ambos')),
  notas         text,
  estado        text not null default 'pendiente' check (estado in ('pendiente', 'confirmado', 'declinado')),
  asistentes    integer not null default 0 check (asistentes >= 0),
  mensaje       text check (char_length(mensaje) <= 1000),
  abierto_en    timestamptz,
  respondido_en timestamptz,
  creado_en     timestamptz not null default now(),
  constraint asistentes_dentro_de_cupos check (asistentes <= cupos)
);

create table if not exists public.administradores (
  email text primary key
);

alter table public.invitados enable row level security;
alter table public.administradores enable row level security;

create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.administradores
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

drop policy if exists "administradores gestionan invitados" on public.invitados;
create policy "administradores gestionan invitados"
  on public.invitados for all
  to authenticated
  using (public.es_admin())
  with check (public.es_admin());

drop policy if exists "administradores se ven" on public.administradores;
create policy "administradores se ven"
  on public.administradores for select
  to authenticated
  using (public.es_admin());

-- Lo que ve un invitado al abrir su enlace. p_marcar = false para las vistas
-- previas desde el panel, que no deben contar como "abierta".
create or replace function public.ver_invitacion(p_codigo text, p_marcar boolean default true)
returns table (
  numero integer,
  nombre text,
  cupos integer,
  estado text,
  asistentes integer,
  mensaje text,
  respondido_en timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
#variable_conflict use_column
begin
  if p_marcar then
    update public.invitados i
       set abierto_en = coalesce(i.abierto_en, now())
     where i.codigo = upper(p_codigo);
  end if;

  return query
    select i.numero, i.nombre, i.cupos, i.estado, i.asistentes, i.mensaje, i.respondido_en
      from public.invitados i
     where i.codigo = upper(p_codigo);
end;
$$;

-- La respuesta del invitado, validada contra sus cupos.
create or replace function public.responder_invitacion(
  p_codigo text,
  p_asiste boolean,
  p_asistentes integer,
  p_mensaje text
)
returns table (
  numero integer,
  nombre text,
  cupos integer,
  estado text,
  asistentes integer,
  mensaje text,
  respondido_en timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
#variable_conflict use_column
declare
  v public.invitados;
begin
  select * into v from public.invitados i where i.codigo = upper(p_codigo) for update;
  if not found then
    raise exception 'codigo_invalido';
  end if;
  if p_asiste and (p_asistentes is null or p_asistentes < 1 or p_asistentes > v.cupos) then
    raise exception 'asistentes_fuera_de_cupo';
  end if;

  update public.invitados i
     set estado = case when p_asiste then 'confirmado' else 'declinado' end,
         asistentes = case when p_asiste then p_asistentes else 0 end,
         mensaje = nullif(left(btrim(coalesce(p_mensaje, '')), 1000), ''),
         respondido_en = now()
   where i.id = v.id;

  return query
    select i.numero, i.nombre, i.cupos, i.estado, i.asistentes, i.mensaje, i.respondido_en
      from public.invitados i
     where i.id = v.id;
end;
$$;

-- Datos de la boda que se editan desde el panel (fecha, lugares, itinerario,
-- vestimenta, regalos). Una sola fila. La invitación la lee sin sesión; solo
-- los administradores la cambian.
create table if not exists public.evento (
  id             smallint primary key default 1 check (id = 1),
  datos          jsonb not null default '{}'::jsonb,
  actualizado_en timestamptz not null default now()
);

alter table public.evento enable row level security;

drop policy if exists "todos leen el evento" on public.evento;
create policy "todos leen el evento"
  on public.evento for select
  to anon, authenticated
  using (true);

drop policy if exists "administradores editan el evento" on public.evento;
create policy "administradores editan el evento"
  on public.evento for all
  to authenticated
  using (public.es_admin())
  with check (public.es_admin());

grant select on public.evento to anon, authenticated;
grant insert, update on public.evento to authenticated;

-- Fotos que se suben desde el panel: la principal, las de la pareja y las de
-- referencia de vestimenta. El panel las reduce a JPG antes de subirlas.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fotos', 'fotos', true, 10485760, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "administradores ven las fotos" on storage.objects;
create policy "administradores ven las fotos"
  on storage.objects for select
  to authenticated
  using (bucket_id = 'fotos' and public.es_admin());

drop policy if exists "administradores suben fotos" on storage.objects;
create policy "administradores suben fotos"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'fotos' and public.es_admin());

drop policy if exists "administradores cambian fotos" on storage.objects;
create policy "administradores cambian fotos"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'fotos' and public.es_admin())
  with check (bucket_id = 'fotos' and public.es_admin());

drop policy if exists "administradores borran fotos" on storage.objects;
create policy "administradores borran fotos"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'fotos' and public.es_admin());

revoke all on function public.ver_invitacion(text, boolean) from public;
revoke all on function public.responder_invitacion(text, boolean, integer, text) from public;
revoke all on function public.es_admin() from public;

grant execute on function public.ver_invitacion(text, boolean) to anon, authenticated;
grant execute on function public.responder_invitacion(text, boolean, integer, text) to anon, authenticated;
grant execute on function public.es_admin() to authenticated;

